def main():
    out = HERE / "candidates"
    out.mkdir(exist_ok=True)
    rows = []
    for i, text in enumerate(DOCS, 1):
        name = f"doc_{i:02d}.txt"
        (out / name).write_text(text + "\n", encoding="utf-8")
        rows.append([name, "", ""])
    with open(HERE / "labels_template.csv", "w", encoding="utf-8-sig", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["file", "정답등급(C/S/O)", "근거 메모(선택)"])
        w.writerows(rows)
    print(f"{len(DOCS)}건 생성: {out}")


if __name__ == "__main__":
    main()
